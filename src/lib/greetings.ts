// チャットを開いたとき（まだ会話がないとき）に出す、社員ごとのあいさつ（固定文・AIは使わない）。
// 社員ごとの話し方（一人称・語尾・口癖）に合わせています。名前は設定で変えても反映されるよう、引数で受け取ります。

const GREETINGS: Record<string, (name: string, role: string) => string> = {
  president: (n) => `お疲れさま！CEOの${n}だよ。任せたい仕事があれば、俺が必要な社員に割り振るね。まずやってみよう！`,
  creative: (n) => `こんにちは、編集の${n}だよ。ぼくは言葉を磨くのが好きなんだ。書きたいことがあれば、気軽に話してくれるとうれしいかもね。`,
  finance: (n) => `${n}です。私は記事の事実や引用元、著作権の確認を担当しています。気になる点があれば、念のため、確認します。`,
  research: (n) => `${n}だよ。僕は市場調査の担当。要点はね、知りたいことを一言で言ってもらえると早いと思う。`,
  bizdev: (n) => `やっほー、${n}だよ！ジャンル選びやブランドづくりは私にまかせて！何から始めよっか？`,
  secretary: (n) => `こんにちは、${n}だよ。Xの投稿の準備は私が見てるね。やることが多くても、大丈夫、整理しよ。`,
  life: (n) => `こんにちは、${n}だよ。私は数字を見ながら、のんびり分析してるんだあ。ゆっくりでいいよ。思いついたことから話してみてねえ。`,
};

export function chatGreeting(id: string, name: string, roleTitle: string): string {
  return GREETINGS[id]?.(name, roleTitle) ?? `${roleTitle}の${name}です。ご用件をどうぞ。`;
}
