// チャットを開いたとき（まだ会話がないとき）に出す、社員ごとのあいさつ（固定文・AIは使わない）。
// 社員ごとの話し方（一人称・語尾・口癖）に合わせています。社員は id（部署）で選び、名前は設定で変えても反映されるよう引数で受け取ります。

const GREETINGS: Record<string, (name: string, role: string) => string> = {
  president: (n) => `お疲れさま！CEOの${n}です。任せたい仕事は俺に言って。すぐ割り振るよ。まずやってみよう！`,
  bizdev: (n) => `やあ、${n}だよ。僕は新しいジャンルやチャンスを探すのが大好きなんだ。気になることがあったら、どんどん話そうよ！`,
  research: (n) => `こんにちは、${n}です。私は市場の調査をしています。気になっていること、まずはゆっくり聞かせてもらえますか。`,
  creative: (n) => `こんにちは、編集の${n}だよ。ぼくは言葉を磨くのが好きなんだ。書きたいことがあれば、気軽に話してね。`,
  secretary: (n) => `どうも、${n}だよ！僕はXの投稿と、読者の反応を見てるんだ。最近気になる話題があったら、いっしょに考えるのが楽しみだね！`,
  finance: (n) => `${n}です。私は記事の事実や引用元、著作権の確認を担当しています。気になる点があれば、念のため、確認します。`,
  life: (n) => `${n}。経営分析の担当。僕は数字を見てる。聞きたいことがあれば、短くどうぞ。`,
};

export function chatGreeting(id: string, name: string, roleTitle: string): string {
  return GREETINGS[id]?.(name, roleTitle) ?? `${roleTitle}の${name}です。ご用件をどうぞ。`;
}
